export function bpmCompatible(bpmA, bpmB) {
  return Math.abs(bpmA - bpmB) <= 6
}

export function genreCompatible(genreA, genreB) {
  if (genreA === genreB) return true
  const infoA = genreFamilies[genreA]
  if (!infoA) return false
  return infoA.transitionTo.includes(genreB)
}

export function keyCompatible(keyA, keyB) {
  const camelotMap = {
    'Ab': '1B', 'Fm': '1A', 'Eb': '2B', 'Cm': '2A', 'Bb': '3B', 'Gm': '3A',
    'F': '4B', 'Dm': '4A', 'C': '5B', 'Am': '5A', 'G': '6B', 'Em': '6A',
    'D': '7B', 'Bm': '7A', 'A': '8B', 'F#m': '8A', 'E': '9B', 'C#m': '9A',
    'B': '10B', 'G#m': '10A', 'F#': '11B', 'Ebm': '11A', 'Db': '12B', 'Bbm': '12A',
  }
  const a = camelotMap[keyA]
  const b = camelotMap[keyB]
  if (!a || !b) return null
  const numA = parseInt(a), numB = parseInt(b)
  const letterA = a.slice(-1), letterB = b.slice(-1)
  if (numA === numB) return true
  if (letterA === letterB && (Math.abs(numA - numB) === 1 || Math.abs(numA - numB) === 11)) return true
  return false
}

export function energyLabel(energy) {
  if (energy <= 3) return 'Low'
  if (energy <= 6) return 'Medium'
  if (energy <= 8) return 'High'
  return 'Peak'
}

export function getGenres() {
  return [...new Set(catalog.map(t => t.genre))].sort()
}

export function getTracksByGenre(genre) {
  return catalog.filter(t => t.genre === genre)
}

export function getArtists() {
  return [...new Set(catalog.map(t => t.artist))].sort()
}

export function getTracksByArtist(artist) {
  const lower = artist.toLowerCase()
  return catalog.filter(t => t.artist.toLowerCase().includes(lower))
}

export function searchCatalog(query) {
  const lower = query.toLowerCase()
  return catalog.filter(t =>
    t.title.toLowerCase().includes(lower) ||
    t.artist.toLowerCase().includes(lower) ||
    t.genre.toLowerCase().includes(lower)
  )
}

let nextId = catalog.length + 1

export function addTrackToCatalog(track) {
  const newTrack = { id: nextId++, ...track }
  catalog.push(newTrack)
  return newTrack
}

export function addTracksToCatalog(tracks) {
  return tracks.map(t => addTrackToCatalog(t))
}
